//! Bounded, product-neutral residual composition and research evaluation DTOs.
//! These serializable values confer no live runtime or deployment authority.
//! Validate mutable DTOs after deserialization and before execution; enforce
//! transport byte limits before deserializing untrusted input.

use crate::{
    MAX_TOKEN_PIECE_BYTES, ModelFingerprint, NativeError, invalid_config, validate_id,
    validate_sha256,
};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::collections::BTreeSet;

pub const MAX_RESIDUAL_EVALUATION_PROFILES: usize = 8;
pub const MAX_RESIDUAL_EVALUATION_CASES: usize = 64;
/// Sum of layer entries across all profiles, counting shared layers repeatedly.
pub const MAX_RESIDUAL_EVALUATION_COORDINATES: usize = 16;
pub const MAX_RESIDUAL_EVALUATION_MODEL_LAYERS: u32 = 4_096;
pub const MAX_RESIDUAL_EVALUATION_WIDTH: usize = 65_536;
pub const MAX_RESIDUAL_EVALUATION_CONTEXT_TOKENS: usize = 4_096;
pub const MAX_RESIDUAL_EVALUATION_NEW_TOKENS: u32 = 256;
/// At most 1 MiB per case, further bounded by the actual generated token count.
/// Together with the case cap this bounds raw generated bytes to 64 MiB per output.
pub const MAX_RESIDUAL_EVALUATION_GENERATED_BYTES: usize =
    MAX_RESIDUAL_EVALUATION_NEW_TOKENS as usize * MAX_TOKEN_PIECE_BYTES;
pub const MAX_RESIDUAL_EVALUATION_INPUT_TOKENS: usize = 32_768;
pub const MAX_RESIDUAL_EVALUATION_WORK_TOKENS: u64 = 65_536;
pub const MAX_RESIDUAL_EVALUATION_VOCABULARY: usize = 1_048_576;
/// Dense f32 control storage is at most 64 MiB, excluding bounded scratch space.
pub const MAX_RESIDUAL_EVALUATION_CONTROL_VALUES: usize = 16_777_216;
pub const MAX_RESIDUAL_EVALUATION_NORM: f32 = 100.0;
pub const MAX_RESIDUAL_EVALUATION_ABS_COEFFICIENT: f32 = 100.0;
pub const RESIDUAL_EVALUATION_SAMPLING: &str = "greedy_argmax_lowest_token_id_tie_v1";
pub const RESIDUAL_EVALUATION_INTERVENTION: &str =
    "composed_post_block_residual_addition_from_last_prefix_token_v1";

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct ResidualControlProfile {
    pub id: String,
    /// Caller-supplied provenance digest. A valid digest is not source verification.
    pub source_sha256: String,
    /// Zero-based post-block indices, restricted to `1..=n_layers - 2`.
    pub layers: Vec<u32>,
    /// One unit axis per selected layer. A case's single coefficient for this
    /// profile multiplies every axis; there is no implicit per-layer gain.
    pub directions: Vec<Vec<f32>>,
}

impl ResidualControlProfile {
    pub fn validate(&self) -> Result<(), NativeError> {
        validate_id("residual profile id", &self.id)?;
        validate_sha256("residual profile source_sha256", &self.source_sha256)?;
        if self.layers.is_empty()
            || self.layers.len() > MAX_RESIDUAL_EVALUATION_COORDINATES
            || self.directions.len() != self.layers.len()
            || self
                .layers
                .iter()
                .any(|&v| v == 0 || v > MAX_RESIDUAL_EVALUATION_MODEL_LAYERS - 2)
            || self.layers.iter().collect::<BTreeSet<_>>().len() != self.layers.len()
        {
            return Err(invalid_config("invalid residual profile layer coordinates"));
        }
        let width = self.directions[0].len();
        if !(1..=MAX_RESIDUAL_EVALUATION_WIDTH).contains(&width) {
            return Err(invalid_config("invalid residual profile width"));
        }
        for axis in &self.directions {
            if axis.len() != width || axis.iter().any(|v| !v.is_finite()) {
                return Err(invalid_config(
                    "residual profile axes must have equal width and finite values",
                ));
            }
            let norm_squared: f64 = axis.iter().map(|&v| f64::from(v).powi(2)).sum();
            if (norm_squared - 1.0).abs() > 1e-5 {
                return Err(invalid_config("residual profile axes must be unit length"));
            }
        }
        Ok(())
    }

    /// Canonical, ordered profile identity, including provenance and float bits.
    pub fn sha256(&self) -> Result<String, NativeError> {
        self.validate()?;
        let mut hash = Sha256::new();
        hash.update(b"llama-native.residual-control-profile.v1\0");
        hash_profile(&mut hash, self);
        Ok(format!("{:x}", hash.finalize()))
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct ResidualEvaluationCase {
    pub id: String,
    pub prefix: Vec<i32>,
    /// Empty disables teacher forcing. Target means exclude prefix tokens.
    pub continuation: Vec<i32>,
    /// One coefficient per request profile, in request order.
    pub coefficients: Vec<f32>,
    /// Zero disables generation. Rollout starts from the prefix independently
    /// of the supplied continuation, with identical residual intervention.
    pub maximum_new_tokens: u32,
    /// Recorded and hashed for reproducibility, but unused by greedy argmax.
    pub seed: u32,
}

impl ResidualEvaluationCase {
    pub fn validate(&self) -> Result<(), NativeError> {
        validate_id("residual evaluation case id", &self.id)?;
        validate_coefficients(&self.coefficients)?;
        if self.prefix.is_empty()
            || self.prefix.len() > MAX_RESIDUAL_EVALUATION_CONTEXT_TOKENS
            || self.continuation.len() > MAX_RESIDUAL_EVALUATION_CONTEXT_TOKENS
            || self.prefix.iter().chain(&self.continuation).any(|&v| v < 0)
            || self.maximum_new_tokens > MAX_RESIDUAL_EVALUATION_NEW_TOKENS
            || (self.continuation.is_empty() && self.maximum_new_tokens == 0)
        {
            return Err(invalid_config(
                "invalid residual evaluation case tokens or requested work",
            ));
        }
        if self.required_context_tokens() > MAX_RESIDUAL_EVALUATION_CONTEXT_TOKENS {
            return Err(invalid_config(
                "residual evaluation prefix and continuation or rollout exceed context cap",
            ));
        }
        Ok(())
    }

    fn required_context_tokens(&self) -> usize {
        self.prefix.len()
            + self
                .continuation
                .len()
                .max(self.maximum_new_tokens as usize)
    }

    fn work_tokens(&self) -> u64 {
        let forced = if self.continuation.is_empty() {
            0
        } else {
            2 * (self.prefix.len() + self.continuation.len()) as u64
        };
        let rollout = if self.maximum_new_tokens == 0 {
            0
        } else {
            self.prefix.len() as u64 + u64::from(self.maximum_new_tokens)
        };
        forced + rollout
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct ResidualEvaluationRequest {
    pub request_id: String,
    pub model_id: String,
    pub expected_model_sha256: String,
    pub profiles: Vec<ResidualControlProfile>,
    pub cases: Vec<ResidualEvaluationCase>,
    /// Bound on the actual composed f32 stack, not the coefficient vector.
    pub maximum_control_norm: f32,
}

impl ResidualEvaluationRequest {
    pub fn validate(&self) -> Result<(), NativeError> {
        self.validate_structure()?;
        // Model-independent norm admission uses only selected rows; the live
        // boundary additionally checks their indices and dense storage size.
        for case in &self.cases {
            compose_sparse(self, case)?;
        }
        Ok(())
    }

    fn validate_structure(&self) -> Result<(), NativeError> {
        validate_id("residual evaluation request_id", &self.request_id)?;
        validate_id("residual evaluation model_id", &self.model_id)?;
        validate_sha256(
            "residual expected_model_sha256",
            &self.expected_model_sha256,
        )?;
        if self.profiles.is_empty()
            || self.profiles.len() > MAX_RESIDUAL_EVALUATION_PROFILES
            || self.cases.is_empty()
            || self.cases.len() > MAX_RESIDUAL_EVALUATION_CASES
            || !self.maximum_control_norm.is_finite()
            || !(0.0..=MAX_RESIDUAL_EVALUATION_NORM).contains(&self.maximum_control_norm)
        {
            return Err(invalid_config(
                "invalid residual evaluation counts or control norm limit",
            ));
        }
        let mut ids = BTreeSet::new();
        let mut coordinates = 0;
        let mut width = None;
        for profile in &self.profiles {
            profile.validate()?;
            if !ids.insert(profile.id.as_str()) {
                return Err(invalid_config("duplicate residual profile id"));
            }
            coordinates += profile.layers.len();
            if coordinates > MAX_RESIDUAL_EVALUATION_COORDINATES {
                return Err(invalid_config(
                    "residual evaluation total coordinate cap exceeded",
                ));
            }
            let current_width = profile.directions[0].len();
            if width.is_some_and(|width| width != current_width) {
                return Err(invalid_config("residual profiles have inconsistent widths"));
            }
            width = Some(current_width);
        }
        ids.clear();
        let mut input_tokens = 0;
        let mut work_tokens = 0;
        for case in &self.cases {
            case.validate()?;
            if case.coefficients.len() != self.profiles.len() || !ids.insert(case.id.as_str()) {
                return Err(invalid_config(
                    "duplicate evaluation case id or mismatched coefficient count",
                ));
            }
            input_tokens += case.prefix.len() + case.continuation.len();
            work_tokens += case.work_tokens();
            if input_tokens > MAX_RESIDUAL_EVALUATION_INPUT_TOKENS
                || work_tokens > MAX_RESIDUAL_EVALUATION_WORK_TOKENS
            {
                return Err(invalid_config(
                    "residual evaluation input or work token cap exceeded",
                ));
            }
        }
        Ok(())
    }

    /// Conservative decodes for controlled/reference teacher forcing plus one
    /// independent greedy rollout. No architecture-dependent FLOP guarantee.
    pub fn estimated_token_evaluations(&self) -> Result<u64, NativeError> {
        self.validate()?;
        Ok(self
            .cases
            .iter()
            .map(ResidualEvaluationCase::work_tokens)
            .sum())
    }

    pub fn validate_for_model(
        &self,
        n_layers: u32,
        width: usize,
        vocabulary_size: usize,
        context_tokens: usize,
    ) -> Result<(), NativeError> {
        self.validate()?;
        self.validate_shape(n_layers, width)?;
        if !(1..=MAX_RESIDUAL_EVALUATION_VOCABULARY).contains(&vocabulary_size)
            || !(1..=MAX_RESIDUAL_EVALUATION_CONTEXT_TOKENS).contains(&context_tokens)
        {
            return Err(invalid_config(
                "invalid residual evaluation vocabulary or execution context",
            ));
        }
        for case in &self.cases {
            if case.required_context_tokens() > context_tokens
                || case
                    .prefix
                    .iter()
                    .chain(&case.continuation)
                    .any(|&v| v as usize >= vocabulary_size)
            {
                return Err(invalid_config(
                    "residual evaluation case exceeds model vocabulary or context",
                ));
            }
        }
        Ok(())
    }

    fn validate_shape(&self, n_layers: u32, width: usize) -> Result<usize, NativeError> {
        if !(3..=MAX_RESIDUAL_EVALUATION_MODEL_LAYERS).contains(&n_layers)
            || !(1..=MAX_RESIDUAL_EVALUATION_WIDTH).contains(&width)
            || self.profiles.iter().any(|p| {
                p.layers.iter().any(|&v| v > n_layers - 2)
                    || p.directions.iter().any(|v| v.len() != width)
            })
        {
            return Err(invalid_config(
                "unsupported residual model shape or profile coordinates",
            ));
        }
        let count = width
            .checked_mul(n_layers as usize - 1)
            .filter(|&n| n <= MAX_RESIDUAL_EVALUATION_CONTROL_VALUES)
            .ok_or_else(|| invalid_config("dense residual control exceeds 64 MiB"))?;
        Ok(count)
    }

    /// Canonical, domain-separated, length-delimited digest of ALL request
    /// inputs in order, preserving exact f32 bits (including signed zero).
    pub fn sha256(&self) -> Result<String, NativeError> {
        self.validate()?;
        let mut hash = Sha256::new();
        hash.update(b"llama-native.residual-evaluation-request.v1\0");
        for text in [
            &self.request_id,
            &self.model_id,
            &self.expected_model_sha256,
        ] {
            hash_bytes(&mut hash, text.as_bytes());
        }
        hash_len(&mut hash, self.profiles.len());
        for profile in &self.profiles {
            hash_profile(&mut hash, profile);
        }
        hash_len(&mut hash, self.cases.len());
        for case in &self.cases {
            hash_bytes(&mut hash, case.id.as_bytes());
            for tokens in [&case.prefix, &case.continuation] {
                hash_len(&mut hash, tokens.len());
                for token in tokens {
                    hash.update(token.to_le_bytes());
                }
            }
            hash_len(&mut hash, case.coefficients.len());
            for coefficient in &case.coefficients {
                hash.update(coefficient.to_bits().to_le_bytes());
            }
            hash.update(case.maximum_new_tokens.to_le_bytes());
            hash.update(case.seed.to_le_bytes());
        }
        hash.update(self.maximum_control_norm.to_bits().to_le_bytes());
        Ok(format!("{:x}", hash.finalize()))
    }
}

/// Compose a request member into llama.cpp's dense cvec layout: the row for
/// post-block index `layer` starts at `(layer - 1) * width`; unused rows are zero.
/// Sum shared-layer contributions in f64, round once to f32, then measure the
/// ACTUAL returned stack. Excess norm is an error, never silent clipping.
/// Validates request structure and this case; use request.validate() for all
/// cases at admission, avoiding quadratic batch composition during execution.
pub fn compose_residual_control(
    request: &ResidualEvaluationRequest,
    case: &ResidualEvaluationCase,
    n_layers: u32,
    width: usize,
) -> Result<Vec<f32>, NativeError> {
    request.validate_structure()?;
    validate_case_membership(request, case)?;
    let count = request.validate_shape(n_layers, width)?;
    let (sparse, _) = compose_sparse(request, case)?;
    let mut dense = vec![0.0; count];
    for (layer, values) in sparse {
        let start = (layer as usize - 1) * width;
        dense[start..start + width].copy_from_slice(&values);
    }
    Ok(dense)
}

/// Recompute the same actual f32 stack norm without allocating unused rows.
pub fn residual_control_stack_norm(
    request: &ResidualEvaluationRequest,
    case: &ResidualEvaluationCase,
) -> Result<f64, NativeError> {
    request.validate_structure()?;
    validate_case_membership(request, case)?;
    compose_sparse(request, case).map(|(_, norm)| norm)
}

fn validate_case_membership(
    request: &ResidualEvaluationRequest,
    case: &ResidualEvaluationCase,
) -> Result<(), NativeError> {
    if !request
        .cases
        .iter()
        .any(|member| member == case && same_float_bits(&member.coefficients, &case.coefficients))
    {
        return Err(invalid_config(
            "residual evaluation case is not an exact request member",
        ));
    }
    Ok(())
}

type SparseControl = Vec<(u32, Vec<f32>)>;

// Only call after request validation: all coefficient indices and widths match.
fn compose_sparse(
    request: &ResidualEvaluationRequest,
    case: &ResidualEvaluationCase,
) -> Result<(SparseControl, f64), NativeError> {
    let layers: BTreeSet<u32> = request
        .profiles
        .iter()
        .flat_map(|p| p.layers.iter().copied())
        .collect();
    let width = request.profiles[0].directions[0].len();
    let mut sparse = Vec::with_capacity(layers.len());
    let mut norm_squared = 0.0;
    for layer in layers {
        let mut sum = vec![0.0_f64; width];
        for (profile, &coefficient) in request.profiles.iter().zip(&case.coefficients) {
            if let Some(index) = profile.layers.iter().position(|&v| v == layer) {
                for (sum, &value) in sum.iter_mut().zip(&profile.directions[index]) {
                    *sum += f64::from(coefficient) * f64::from(value);
                }
            }
        }
        let values: Vec<f32> = sum.into_iter().map(|v| v as f32).collect();
        for &value in &values {
            if !value.is_finite() {
                return Err(invalid_config("nonfinite composed residual value"));
            }
            norm_squared += f64::from(value).powi(2);
        }
        sparse.push((layer, values));
    }
    let norm = norm_squared.sqrt();
    if !norm.is_finite() || norm > f64::from(request.maximum_control_norm) {
        return Err(invalid_config(
            "actual composed residual stack exceeds requested L2 bound",
        ));
    }
    Ok((sparse, norm))
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum ResidualEvaluationTermination {
    /// EOG was selected but is NOT included in generated_token_ids. Its
    /// selection consumes one maximum_new_tokens slot. Owner verifies identity.
    Eog,
    TokenLimit,
    NotRequested,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct ResidualEvaluationCaseOutput {
    pub id: String,
    pub coefficients: Vec<f32>,
    pub actual_stack_norm: f64,
    /// Excludes the terminating EOG, if any. Owner must reject other EOG entries.
    pub generated_token_ids: Vec<i32>,
    /// Exact concatenation of the model's token-piece bytes for generated IDs,
    /// retaining special-token bytes but excluding the terminating EOG. No UTF-8
    /// decoding, replacement, normalization, or human-source bytes are implied.
    /// The owner verifies token-piece correspondence; DTO validation only bounds
    /// storage. Some token pieces may be empty, so no minimum byte count applies.
    pub generated_bytes: Vec<u8>,
    pub mean_continuation_logprob: Option<f64>,
    /// Full-vocabulary KL(unmodified reference || controlled), averaged over
    /// supplied continuation targets on the SAME teacher-forced token history.
    /// Does not compare independently generated continuations.
    pub mean_reference_kl: Option<f64>,
    /// Supplied continuation length, not generated token count.
    pub target_token_count: u32,
    pub termination: ResidualEvaluationTermination,
}

impl ResidualEvaluationCaseOutput {
    pub fn validate(&self) -> Result<(), NativeError> {
        validate_id("residual evaluation output case id", &self.id)?;
        validate_coefficients(&self.coefficients)?;
        if !self.actual_stack_norm.is_finite()
            || !(0.0..=f64::from(MAX_RESIDUAL_EVALUATION_NORM)).contains(&self.actual_stack_norm)
            || self.generated_token_ids.len() > MAX_RESIDUAL_EVALUATION_NEW_TOKENS as usize
            || self.generated_token_ids.iter().any(|&v| v < 0)
            || self.target_token_count as usize > MAX_RESIDUAL_EVALUATION_CONTEXT_TOKENS
        {
            return Err(invalid_config("invalid residual evaluation output values"));
        }
        // Token count was bounded above before multiplication. This also forces
        // empty bytes when no token IDs exist, including immediate EOG.
        if self.generated_bytes.len() > self.generated_token_ids.len() * MAX_TOKEN_PIECE_BYTES {
            return Err(invalid_config(
                "residual generated bytes exceed the token-piece byte bound",
            ));
        }
        match (
            self.target_token_count,
            self.mean_continuation_logprob,
            self.mean_reference_kl,
        ) {
            (0, None, None) => {}
            (1.., Some(logprob), Some(kl))
                if logprob.is_finite() && logprob <= 0.0 && kl.is_finite() && kl >= 0.0 => {}
            _ => {
                return Err(invalid_config(
                    "residual target count and finite likelihood/KL evidence disagree",
                ));
            }
        }
        match self.termination {
            ResidualEvaluationTermination::NotRequested
                if !self.generated_token_ids.is_empty() || self.target_token_count == 0 =>
            {
                return Err(invalid_config(
                    "not-requested generation has tokens or no evaluation evidence",
                ));
            }
            ResidualEvaluationTermination::TokenLimit if self.generated_token_ids.is_empty() => {
                return Err(invalid_config(
                    "token-limit termination requires generated tokens",
                ));
            }
            ResidualEvaluationTermination::Eog
                if self.generated_token_ids.len()
                    >= MAX_RESIDUAL_EVALUATION_NEW_TOKENS as usize =>
            {
                return Err(invalid_config("EOG must consume a generation slot"));
            }
            _ => {}
        }
        Ok(())
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct ResidualEvaluationOutput {
    pub request_sha256: String,
    pub model_fingerprint: ModelFingerprint,
    pub execution_fingerprint: ModelFingerprint,
    /// Must equal RESIDUAL_EVALUATION_SAMPLING. No configurable sampler claims.
    pub sampling_method: String,
    pub intervention_semantics: String,
    /// Canonical profile hashes, in request order; includes source digests.
    pub profile_sha256: Vec<String>,
    pub cases: Vec<ResidualEvaluationCaseOutput>,
}

impl ResidualEvaluationOutput {
    pub fn validate(&self) -> Result<(), NativeError> {
        validate_sha256("residual evaluation request_sha256", &self.request_sha256)?;
        validate_fingerprint(&self.model_fingerprint)?;
        validate_fingerprint(&self.execution_fingerprint)?;
        let mut same_execution = self.model_fingerprint.clone();
        same_execution.context_tokens = self.execution_fingerprint.context_tokens;
        same_execution.batch_tokens = self.execution_fingerprint.batch_tokens;
        same_execution.max_sequences = self.execution_fingerprint.max_sequences;
        same_execution
            .rope_config_sha256
            .clone_from(&self.execution_fingerprint.rope_config_sha256);
        same_execution
            .kv_layout_sha256
            .clone_from(&self.execution_fingerprint.kv_layout_sha256);
        if same_execution != self.execution_fingerprint
            || !(1..=MAX_RESIDUAL_EVALUATION_CONTEXT_TOKENS as u32)
                .contains(&self.execution_fingerprint.context_tokens)
            || self.execution_fingerprint.max_sequences != 1
            || self.execution_fingerprint.batch_tokens == 0
            || self.execution_fingerprint.batch_tokens > self.execution_fingerprint.context_tokens
            || self.sampling_method != RESIDUAL_EVALUATION_SAMPLING
            || self.intervention_semantics != RESIDUAL_EVALUATION_INTERVENTION
            || self.profile_sha256.is_empty()
            || self.profile_sha256.len() > MAX_RESIDUAL_EVALUATION_PROFILES
            || self.cases.is_empty()
            || self.cases.len() > MAX_RESIDUAL_EVALUATION_CASES
        {
            return Err(invalid_config(
                "invalid residual evaluation output identity, semantics, or dimensions",
            ));
        }
        for hash in &self.profile_sha256 {
            validate_sha256("residual profile_sha256", hash)?;
        }
        let mut ids = BTreeSet::new();
        for case in &self.cases {
            case.validate()?;
            if !ids.insert(case.id.as_str()) || case.coefficients.len() != self.profile_sha256.len()
            {
                return Err(invalid_config(
                    "duplicate residual output case or mismatched coefficients",
                ));
            }
        }
        Ok(())
    }

    /// Validates a research receipt, not runtime authority. Live vocabulary and
    /// actual EOG identity still belong to the model-owning worker.
    pub fn validate_for_request(
        &self,
        request: &ResidualEvaluationRequest,
    ) -> Result<(), NativeError> {
        self.validate()?;
        if self.request_sha256 != request.sha256()?
            || self.model_fingerprint.model_id != request.model_id
            || self.model_fingerprint.model_sha256 != request.expected_model_sha256
            || self.cases.len() != request.cases.len()
            || self.profile_sha256
                != request
                    .profiles
                    .iter()
                    .map(ResidualControlProfile::sha256)
                    .collect::<Result<Vec<_>, _>>()?
        {
            return Err(invalid_config(
                "residual evaluation output does not match request identity",
            ));
        }
        for (row, case) in self.cases.iter().zip(&request.cases) {
            let (_, norm) = compose_sparse(request, case)?;
            if row.id != case.id
                || !same_float_bits(&row.coefficients, &case.coefficients)
                || row.target_token_count as usize != case.continuation.len()
                || row.actual_stack_norm > f64::from(request.maximum_control_norm)
                || (row.actual_stack_norm - norm).abs() > 1e-10 * norm.max(1.0)
                || case.required_context_tokens()
                    > self.execution_fingerprint.context_tokens as usize
            {
                return Err(invalid_config(
                    "residual output case disagrees with requested coefficients, norm, targets, or context",
                ));
            }
            let generated = row.generated_token_ids.len();
            let maximum = case.maximum_new_tokens as usize;
            let consistent = match row.termination {
                ResidualEvaluationTermination::NotRequested => maximum == 0 && generated == 0,
                ResidualEvaluationTermination::TokenLimit => maximum > 0 && generated == maximum,
                ResidualEvaluationTermination::Eog => maximum > 0 && generated < maximum,
            };
            if !consistent {
                return Err(invalid_config(
                    "residual generation count and termination disagree",
                ));
            }
        }
        Ok(())
    }
}

fn validate_coefficients(values: &[f32]) -> Result<(), NativeError> {
    if values.is_empty()
        || values.len() > MAX_RESIDUAL_EVALUATION_PROFILES
        || values
            .iter()
            .any(|v| !v.is_finite() || v.abs() > MAX_RESIDUAL_EVALUATION_ABS_COEFFICIENT)
    {
        return Err(invalid_config(
            "residual coefficients must be finite and bounded",
        ));
    }
    Ok(())
}

fn same_float_bits(left: &[f32], right: &[f32]) -> bool {
    left.len() == right.len()
        && left
            .iter()
            .zip(right)
            .all(|(left, right)| left.to_bits() == right.to_bits())
}

fn validate_fingerprint(fingerprint: &ModelFingerprint) -> Result<(), NativeError> {
    for (name, value) in [
        ("model_id", &fingerprint.model_id),
        ("binding_version", &fingerprint.binding_version),
        ("build_id", &fingerprint.build_id),
        ("backend", &fingerprint.backend),
    ] {
        validate_id(name, value)?;
    }
    for (name, value) in [
        ("model_sha256", &fingerprint.model_sha256),
        ("tokenizer_sha256", &fingerprint.tokenizer_sha256),
        ("chat_template_sha256", &fingerprint.chat_template_sha256),
        ("rope_config_sha256", &fingerprint.rope_config_sha256),
        ("kv_layout_sha256", &fingerprint.kv_layout_sha256),
    ] {
        validate_sha256(name, value)?;
    }
    if let Some(value) = &fingerprint.multimodal_projector_sha256 {
        validate_sha256("multimodal_projector_sha256", value)?;
    }
    Ok(())
}

fn hash_len(hash: &mut Sha256, length: usize) {
    hash.update((length as u64).to_le_bytes());
}
fn hash_bytes(hash: &mut Sha256, bytes: &[u8]) {
    hash_len(hash, bytes.len());
    hash.update(bytes);
}
fn hash_profile(hash: &mut Sha256, profile: &ResidualControlProfile) {
    hash_bytes(hash, profile.id.as_bytes());
    hash_bytes(hash, profile.source_sha256.as_bytes());
    hash_len(hash, profile.layers.len());
    for layer in &profile.layers {
        hash.update(layer.to_le_bytes());
    }
    hash_len(hash, profile.directions.len());
    for axis in &profile.directions {
        hash_len(hash, axis.len());
        for value in axis {
            hash.update(value.to_bits().to_le_bytes());
        }
    }
}

